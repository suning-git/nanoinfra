"""
Checkpoint management for FSDP models.

Provides:
- DCP entries named by intent: save_checkpoint_dcp (write), load_checkpoint_dcp
  (restore weights + optimizer = a resume), load_model_only (restore weights = an
  init). Around them: metadata recovery and validation (load_metadata,
  get_model_config, config_from_meta, _validate_model_config), source resolution
  (resolve_checkpoint_path, find_latest_checkpoint: resume_from is null, an explicit path (a checkpoint, or a run
  directory -> its newest complete step_*), or `auto` = the newest complete step_* under save_dir)
  and retention (should_save_checkpoint, cleanup_old_checkpoints)
- High-level saving (save_checkpoint_if_needed) and loading (load_checkpoint_if_needed)
  for core training
- The run's data snapshot from every rank's (merge_data_snapshots), which save_checkpoint_if_needed writes
"""

import os
import json
import glob
import re
import shutil
import types
import typing
from dataclasses import asdict, is_dataclass
import torch
import torch.distributed.checkpoint as dcp
from torch.distributed.checkpoint import FileSystemWriter, FileSystemReader
from torch.distributed.checkpoint.state_dict import get_model_state_dict, get_state_dict, set_state_dict
from typing import List, Optional, Dict, Any

from core.utils import print0


def save_checkpoint_dcp(
    checkpoint_dir: str,
    model,
    optimizers: List,
    meta_data: Dict[str, Any],
    rank: int = 0,
    world_size: int = 1,
    dataloader_state: Optional[Dict] = None,
    replace_existing: bool = False,
) -> None:
    """
    Save FSDP checkpoint using DCP.

    Args:
        checkpoint_dir: Directory to save checkpoint (created if not exists)
        model: FSDP model (contains DTensor parameters)
        optimizers: List of optimizers
        meta_data: Dictionary of metadata to save (must include 'step'). It is written to meta.json and read back on
            resume, so what goes in must come back as it was: dict (string keys), list, str, int, float, bool, None;
            no tuples, numpy numbers or tensors (see DataSource.get_state). Whoever puts a value in tests that.
        rank: Current rank
        world_size: Total number of ranks
        dataloader_state: Optional dataloader state for resuming (written to meta.json: must read back from JSON
            unchanged, see DataSource.get_state)
        replace_existing: delete an existing checkpoint_dir first (save_checkpoint_if_needed re-saving the same step)

    Saves:
        - checkpoint_dir/.metadata (JSON, generated by DCP)
        - checkpoint_dir/__0_0.distcp, __1_0.distcp, ... (sharded)
        - checkpoint_dir/meta.json (custom metadata + dataloader_state, rank 0 only)
    """
    if replace_existing:
        if rank == 0 and os.path.exists(checkpoint_dir):
            shutil.rmtree(checkpoint_dir)
        if world_size > 1:
            torch.distributed.barrier()              # every rank waits for rank 0's deletion

    # Create checkpoint directory
    os.makedirs(checkpoint_dir, exist_ok=True)

    # Use get_state_dict() to properly handle FSDP model and optimizer states
    # Returns tuple: (model_state_dict, optim_state_dict)
    model_state_dict, optim_state_dict = get_state_dict(model, optimizers)

    # Build state_dict for DCP
    state_dict = {
        "model": model_state_dict,
        "optimizer": optim_state_dict,
    }

    # DCP save (all ranks participate, each writes its own shard)
    # overwrite=True: Handle NFS cache inconsistency in multi-node environments
    dcp.save(
        state_dict=state_dict,
        storage_writer=FileSystemWriter(checkpoint_dir, overwrite=True),
    )

    # Save custom metadata (rank 0 only)
    if rank == 0:
        meta_path = os.path.join(checkpoint_dir, "meta.json")
        with open(meta_path, "w") as f:
            json.dump(_assemble_meta(meta_data, model, dataloader_state), f, indent=2)


def _assemble_meta(meta_data, model, dataloader_state):
    """meta.json's content: the caller's metadata, the data snapshot, and the model's own description."""
    # Merge dataloader_state into metadata if provided
    if dataloader_state is not None:
        meta_data = {**meta_data, 'dataloader_state': dataloader_state}

    # Self-description: record the architecture this checkpoint was trained
    # with (model.config — LMSystem exposes the trunk's config). The live
    # model is the ONLY authority for this key, so it is written
    # UNCONDITIONALLY — a caller-supplied 'model_config' is by definition
    # less authoritative than the model being saved. Loaders recover it via
    # config_from_meta(); _validate_model_config audits every load
    # against it. A config-less model produces an old-format checkpoint
    # (validation skips: you cannot record what does not exist).
    cfg = getattr(model, 'config', None)
    if is_dataclass(cfg):
        meta_data = {**meta_data, 'model_config': asdict(cfg)}
    # Architecture tag: an ASSEMBLY fact recorded by build_system onto the
    # System (type(trunk) at save time would lie — fully_shard rewrites the
    # instance's class to FSDP{ClassName}). Loaders audit the caller's
    # trunk_cls choice against it (load_system's checked default).
    arch = getattr(model, 'arch', None)
    if arch is not None:
        meta_data = {**meta_data, 'model_arch': arch}
    # Storage precision: what the parameters, and so their gradients and AdamW moments, are
    # stored in, read off the live parameters (buffers are not storage choices). For people and tools reading
    # meta.json; the loaders check against the dtypes in DCP's .metadata instead (stored_tensor_dtypes).
    stored = _dtype_summary(p.dtype for p in model.parameters())
    if stored is not None:
        meta_data = {**meta_data, 'param_dtype': stored}
    history = getattr(model, 'param_dtype_history', None)
    if history:
        meta_data = {**meta_data, 'param_dtype_history': history}
    return meta_data


# ---- storage precision -------------------------------------------------------------------------------------------
# What the parameters are stored in (bf16 or fp32, build_system's param_dtype) is a property of a run: the gradients
# and the AdamW moments follow it. DCP converts a tensor whose stored dtype differs from the live template's on load,
# without a word, so the loaders compare the two first. The stored dtypes come from DCP's own .metadata, which records
# each tensor as written; meta.json's 'param_dtype' is a summary for people and tools, and checkpoints from before it
# existed are checked the same way.

_STORAGE_DTYPES = (torch.bfloat16, torch.float32)       # the storages build_system offers; the only conversions allowed


def _dtype_name(dtype) -> str:
    return str(dtype).removeprefix("torch.")


def _dtype_summary(dtypes) -> Optional[Any]:
    """A set of dtypes as meta.json records it: one name ('bfloat16', 'float32'), or the sorted names when they are
    mixed; None when there are none."""
    names = sorted({_dtype_name(d) for d in dtypes})
    if not names:
        return None
    return names[0] if len(names) == 1 else names


def stored_tensor_dtypes(checkpoint_dir: str, prefix: str) -> Dict[str, torch.dtype]:
    """{key: dtype} of the tensors a DCP checkpoint stores under `prefix` ('model' or 'optimizer'), read from DCP's
    .metadata through its reader (no tensor data is read). Keys are the state-dict keys below the prefix, flattened
    the way DCP flattens them: 'trunk.transformer.wte.weight', 'state.trunk.transformer.wte.weight.exp_avg'."""
    md = FileSystemReader(checkpoint_dir).read_metadata()
    head = prefix + "."
    return {key[len(head):]: entry.properties.dtype for key, entry in md.state_dict_metadata.items()
            if key.startswith(head) and getattr(entry, "properties", None) is not None}


def _buffer_keys(model) -> set:
    """The live buffers' names as get_model_state_dict keys them: compile and activation-checkpoint wrappers add a
    name segment that the state dict leaves out (core compiles in place and FSDP2 adds none). The storage check skips
    buffers (a buffer's dtype is not a storage choice, and some models change it during training) and covers every
    other tensor of the model state. Buffers are the ones named, so that the check fails closed: a key whose wrapper
    segment is not stripped here (torch DDP's 'module.', say) reads as a parameter, refused, not as a buffer, noted;
    and a tied weight's second name, which named_parameters() leaves out, is checked like the first. A buffer shared
    by two modules is listed under both names (remove_duplicate=False), as the state dict keys it."""
    return {n.replace("_orig_mod.", "").replace("_checkpoint_wrapped_module.", "")
            for n, _ in model.named_buffers(remove_duplicate=False)}


def _optimized_param(key: str) -> str:
    """'state.trunk.lin.weight.exp_avg' -> 'trunk.lin.weight'."""
    return key[len("state."):].rsplit(".", 1)[0]


def _live_optimizer_dtypes(optim_state_dict) -> Dict[str, torch.dtype]:
    """The live optimizer state's tensors keyed as stored_tensor_dtypes(..., 'optimizer') keys them."""
    return {f"state.{fqn}.{name}": t.dtype for fqn, state in optim_state_dict.get("state", {}).items()
            for name, t in state.items() if isinstance(t, torch.Tensor)}


def _dtype_changes(checkpoint_dir: str, prefix: str, live: Dict[str, torch.dtype]) -> List[tuple]:
    """[(key, stored dtype, live dtype)] wherever the checkpoint stores a tensor in another dtype than the live one
    that is about to receive it. A live tensor missing from the checkpoint's metadata raises: the check must not pass
    by skipping what it cannot see (DCP itself would fail on the load)."""
    stored = stored_tensor_dtypes(checkpoint_dir, prefix)
    missing = [k for k in live if k not in stored]
    if missing:
        raise ValueError(f"{checkpoint_dir}: {len(missing)} {prefix} tensor(s) of the live model are not in the "
                         f"checkpoint's DCP metadata, e.g. {prefix}.{missing[0]}")
    return [(k, stored[k], d) for k, d in live.items() if stored[k] != d]


def _is_exact_widening(src: torch.dtype, dst: torch.dtype) -> bool:
    """Whether every value of floating dtype src is representable in dst (bf16 -> fp32: yes; fp32 -> bf16: no)."""
    if not (src.is_floating_point and dst.is_floating_point):
        return False
    s, d = torch.finfo(src), torch.finfo(dst)
    return d.eps <= s.eps and d.max >= s.max and d.tiny <= s.tiny


def _describe_changes(changes) -> str:
    """'checkpoint bfloat16 -> this model float32 (exact)' for the distinct (stored, live) pairs of a change list."""
    pairs = sorted({(s, l) for _, s, l in changes}, key=str)
    return "; ".join(f"checkpoint {_dtype_name(s)} -> this model {_dtype_name(l)} "
                     f"({'exact' if _is_exact_widening(s, l) else 'rounded'})" for s, l in pairs)


def load_checkpoint_dcp(
    checkpoint_dir: str,
    model,
    optimizers: List,
    rank: int = 0,
    world_size: int = 1,
    allow_param_dtype_change: bool = False,
) -> Dict[str, Any]:
    """
    Load an FSDP checkpoint using DCP: model weights AND optimizer state (a resume).

    For weights-only initialization, call `load_model_only`. This loader restores
    stored state; the caller owns hyperparameter overrides and LR scheduling.

    Args:
        checkpoint_dir: Directory containing checkpoint
        model: FSDP model (will be filled with loaded weights)
        optimizers: Non-empty list or tuple of optimizers to restore into.
            Restores accumulated state (moments, step counts) and group settings,
            including initial_lr, weight_decay, betas, eps and transient lr.
            Core Trainer recomputes lr from initial_lr before its next update.
        rank: Current rank
        world_size: Total number of ranks
        allow_param_dtype_change: A resume continues the run's own optimizer state, so by default it refuses a model
            whose parameters (or their AdamW moments) are stored in another dtype than the checkpoint's (bf16 vs
            fp32 storage); DCP would otherwise convert them on load without a word. True converts
            deliberately: exact from bf16 to fp32, rounded the other way. The change is appended to
            model.param_dtype_history, which every later checkpoint's meta.json carries. A buffer stored in another
            dtype is converted with a note either way; a tensor not named as a buffer by named_buffers() is checked
            as a parameter. Config key: checkpoint.allow_param_dtype_change.

    Returns:
        meta_data: Dictionary of metadata loaded from checkpoint

    Side effects:
        - model parameters are updated in-place
        - optimizer states and param_groups are updated in-place
        - model.param_dtype_history is replaced: the checkpoint's history, plus this load's change if any

    Raises:
        ValueError: If optimizers is not a non-empty list or tuple, if the checkpoint's
            model_config doesn't match the model's config, if a tensor of the live model or
            optimizer state is missing from the checkpoint's DCP metadata, or if the parameters'
            storage dtype differs from the checkpoint's and allow_param_dtype_change is False
        torch.distributed.checkpoint.api.CheckpointException: DCP restores the
            param_group keys the LIVE optimizer has, key by key; a key the live
            optimizer has and the checkpoint lacks (a checkpoint from before the
            builder pinned initial_lr, or a torch upgrade adding a group key) aborts
            the load with "Missing key in checkpoint state_dict". That exception
            subclasses BaseException, not Exception. Checkpoint-only keys are dropped.
    """
    if not isinstance(optimizers, (list, tuple)) or len(optimizers) == 0:
        raise ValueError(
            "load_checkpoint_dcp restores model + optimizer state and needs a non-empty "
            "list of optimizers (a generator would be consumed by get_state_dict and "
            "leave the optimizer silently unrestored); for weights only call load_model_only")

    # Validate model config before loading
    _validate_model_config(checkpoint_dir, model, rank)

    if not isinstance(allow_param_dtype_change, bool):
        raise TypeError(f"allow_param_dtype_change must be True or False, got {allow_param_dtype_change!r}")

    # Storage precision, the parameters first and from the model alone: get_state_dict(model, optimizers) below
    # initializes an empty optimizer's state (a zero-LR step), and a refused load should leave nothing touched.
    live_model = {k: v.dtype for k, v in get_model_state_dict(model).items() if isinstance(v, torch.Tensor)}
    buffers = _buffer_keys(model) & set(live_model)
    params = set(live_model) - buffers
    model_changes = _dtype_changes(checkpoint_dir, "model", live_model)
    changes = [c for c in model_changes if c[0] not in buffers]
    buffer_changes = [c for c in model_changes if c[0] in buffers]
    _check_dtype_changes(checkpoint_dir, changes, allow_param_dtype_change)
    if buffer_changes and rank == 0:
        print(f"  note: converting buffers on load, {_describe_changes(buffer_changes)}, e.g. {buffer_changes[0][0]}")

    # Use get_state_dict() to create proper template structure
    # This handles fresh optimizers correctly by constructing the full state structure
    model_state_dict, optim_state_dict = get_state_dict(model, optimizers)

    # Then the moments: same parameters but moments stored otherwise is a silent conversion too. ('step' is fp32 on
    # both sides, so it never reads as a change.)
    optim_changes = _dtype_changes(checkpoint_dir, "optimizer", _live_optimizer_dtypes(optim_state_dict))
    _check_dtype_changes(checkpoint_dir, optim_changes, allow_param_dtype_change)

    # Build state_dict for DCP load
    state_dict = {
        "model": model_state_dict,
        "optimizer": optim_state_dict,
    }

    # DCP load (all ranks participate, each reads its own shard)
    dcp.load(
        state_dict=state_dict,
        storage_reader=FileSystemReader(checkpoint_dir),
    )

    # Use set_state_dict() to properly load into model and optimizer
    # This handles DTensor conversion and optimizer state restoration correctly
    set_state_dict(
        model,
        optimizers,
        model_state_dict=state_dict["model"],
        optim_state_dict=state_dict["optimizer"],
    )

    # Load custom metadata
    meta_path = os.path.join(checkpoint_dir, "meta.json")
    with open(meta_path, "r") as f:
        meta_data = json.load(f)

    # Recorded only once the load has succeeded, weights and moments apart. Replaced, not merged, on every resume: an
    # unchanged resume carries the checkpoint's history forward as it was, and a model object loaded twice keeps
    # only the latest checkpoint's.
    history = list(meta_data.get('param_dtype_history', []))
    if changes or optim_changes:
        weights = sorted(k for k, _, _ in changes)
        moments = sorted({_optimized_param(k) for k, _, _ in optim_changes})
        optimized = {_optimized_param(k) for k in _live_optimizer_dtypes(optim_state_dict)}
        history.append({'step': meta_data.get('step'), 'checkpoint': os.path.abspath(checkpoint_dir),
                        'from': _dtype_summary(s for _, s, _ in changes + optim_changes),
                        'to': _dtype_summary(l for _, _, l in changes + optim_changes),
                        'weights': "all" if params and set(weights) == params else weights,
                        'moments': "all" if optimized and set(moments) == optimized else moments})
        if rank == 0:
            print(f"  WARNING: storage dtype changed on resume, as allowed by allow_param_dtype_change: "
                  f"{_describe_changes(changes + optim_changes)} (recorded in param_dtype_history)")
    model.param_dtype_history = history

    return meta_data


def _check_dtype_changes(checkpoint_dir, changes, allow) -> None:
    """Refuse a resume's storage change unless allowed, and any change outside bf16 <-> fp32 even when allowed.
    Every rank reads the same metadata and holds the same dtypes, so every rank raises together (no rank is left
    waiting in a DCP collective)."""
    if not changes:
        return
    unsupported = [c for c in changes if c[1] not in _STORAGE_DTYPES or c[2] not in _STORAGE_DTYPES]
    if unsupported:
        raise ValueError(f"{checkpoint_dir}: {_describe_changes(unsupported)} is not a storage change this loader "
                         f"converts (only bfloat16 <-> float32), e.g. {unsupported[0][0]}")
    if not allow:
        stored = _dtype_summary(s for _, s, _ in changes)
        key = ({"bfloat16": "param_dtype=bf16", "float32": "param_dtype=fp32"}.get(stored, "param_dtype")
               if isinstance(stored, str) else "param_dtype")       # mixed: _dtype_summary gives a list
        raise ValueError(
            f"{checkpoint_dir}: stored in another dtype than this run's model ({_describe_changes(changes)}; "
            f"{len(changes)} tensors, e.g. {changes[0][0]}). A resume does not convert silently: build the model with "
            f"the checkpoint's storage ({key} in the training config; build_system's param_dtype), or set "
            f"checkpoint.allow_param_dtype_change=true to convert deliberately")


def load_metadata(checkpoint_dir: str) -> Dict[str, Any]:
    """
    Load only metadata from checkpoint without loading model/optimizer weights.

    Args:
        checkpoint_dir: Directory containing checkpoint

    Returns:
        meta_data: Dictionary of metadata from checkpoint
    """
    meta_path = os.path.join(checkpoint_dir, "meta.json")
    with open(meta_path, "r") as f:
        meta_data = json.load(f)
    return meta_data


def get_model_config(checkpoint_dir: str) -> Optional[Dict[str, Any]]:
    """
    Get model config from checkpoint metadata.

    Args:
        checkpoint_dir: Directory containing checkpoint

    Returns:
        The recorded model config dict (asdict of the trunk's config the checkpoint
        was trained with) or None if not available (old checkpoint format)
    """
    meta = load_metadata(checkpoint_dir)
    return meta.get('model_config')


def config_from_meta(checkpoint_dir: str, config_cls, sequence_len: Optional[int] = None):
    """Blueprint recovery: rebuild the config a checkpoint was trained with.

    The inverse of the save-side recording (save_checkpoint_dcp writes
    asdict(model.config), tuples as lists, into meta.json['model_config']). Keeping BOTH sides
    of this schema round-trip in core is what stops consumers from re-deriving
    architecture by convention. `config_cls` names the dataclass to rebuild
    into — callers get it from the trunk contract (trunk_cls.Config), so core
    stays ignorant of concrete architectures. `sequence_len` may be
    overridden — an instantiation choice (RoPE tables are computed, not
    stored), not a weight fact; everything else comes from the artifact.

    Returns None for old checkpoints that predate self-description.
    """
    saved = get_model_config(checkpoint_dir)
    if saved is None:
        return None
    # Tolerate schema drift both ways: unknown recorded keys are dropped,
    # fields newer than the recording fall back to config_cls defaults.
    # JSON has no tuples: json writes a tuple as a list, so the record holds lists. A value comes back as its field's
    # annotation says, level by level (tuple[int, ...], tuple[tuple[int, int], ...], list[tuple[...]],
    # Optional[...]; postponed annotations resolved), so lists the config holds stay lists. Where no element
    # types are named (a bare `tuple` annotation, or a field told only by its tuple default) every level comes
    # back a tuple, as before. Values inside a dict are not restored.
    fields = config_cls.__dataclass_fields__
    try:
        hints = typing.get_type_hints(config_cls)
    except Exception:                      # an annotation that does not resolve: each field's own, as written
        hints = {name: f.type for name, f in fields.items()}

    def tuples(x):
        return tuple(tuples(v) for v in x) if isinstance(x, list) else x

    def rebuild(ann, value):
        if not isinstance(value, list):
            return value
        origin, args = typing.get_origin(ann), typing.get_args(ann)
        if origin in (typing.Union, types.UnionType):         # Optional[...]: its one sequence arm, if it has one
            seqs = [a for a in args if a in (tuple, list) or typing.get_origin(a) in (tuple, list)]
            return rebuild(seqs[0], value) if len(seqs) == 1 else value
        if origin is list:
            return [rebuild(args[0], v) for v in value] if args else value
        if ann is tuple or origin is tuple:
            if not args:
                return tuples(value)
            if len(args) == 2 and args[1] is Ellipsis:
                args = (args[0],) * len(value)
            return tuple(map(rebuild, args, value)) if len(args) == len(value) else tuple(value)
        return value

    def restore(name, value):
        value = rebuild(hints.get(name), value)
        return tuples(value) if isinstance(fields[name].default, tuple) and isinstance(value, list) else value
    known = {k: restore(k, v) for k, v in saved.items() if k in fields}
    if sequence_len is not None:
        known['sequence_len'] = sequence_len
    return config_cls(**known)


def _validate_model_config(checkpoint_dir: str, model, rank: int = 0) -> None:
    """
    Validate that checkpoint model_config matches the model's config.

    Raises:
        ValueError: If configs don't match (with clear error message)
    """
    meta = load_metadata(checkpoint_dir)
    saved_config = meta.get('model_config')
    if saved_config is None:
        # Old checkpoint format, skip validation
        return

    if not hasattr(model, 'config'):
        # Model doesn't have config attribute, skip validation
        return

    cfg = model.config
    mismatches = []

    # Architecture identity — strictest of all: same config fields on a
    # different wiring is the ultimate "silently wrong model". Audited only
    # when both sides carry the fact (old checkpoints / bare models don't).
    saved_arch = meta.get('model_arch')
    model_arch = getattr(model, 'arch', None)
    if saved_arch is not None and model_arch is not None and saved_arch != model_arch:
        mismatches.append(f"model_arch: checkpoint={saved_arch}, model={model_arch}")

    # WEIGHT-SHAPING facts — these define what the stored tensors ARE. Some
    # mismatches would not even raise a shape error (n_head reshapes nothing,
    # yet changes attention semantics — a silently wrong model), so all are
    # strictly enforced.
    for field in ('n_layer', 'n_embd', 'n_head', 'n_kv_head', 'vocab_size', 'n_token_types'):
        if field in saved_config and saved_config[field] != getattr(cfg, field, None):
            mismatches.append(
                f"{field}: checkpoint={saved_config[field]}, model={getattr(cfg, field, None)}")

    if mismatches:
        raise ValueError(
            f"Model config mismatch with checkpoint {checkpoint_dir}:\n  " +
            "\n  ".join(mismatches)
        )

    # sequence_len is an INSTANTIATION choice, not a weight fact (RoPE tables
    # are computed, not stored) — running at a different context length than
    # trained is legitimate (e.g. short-context inference). Inform, don't block.
    if saved_config.get('sequence_len') != cfg.sequence_len and rank == 0:
        print(f"  note: sequence_len differs from checkpoint "
              f"(checkpoint={saved_config.get('sequence_len')}, model={cfg.sequence_len}) "
              f"— allowed (instantiation choice)")


def load_model_only(
    checkpoint_dir: str,
    model,
    rank: int = 0,
    world_size: int = 1,
) -> None:
    """
    Load only model weights from checkpoint (for pretrained initialization).

    Optimizer and dataloader states are NOT loaded - training starts fresh.
    Use this for initializing a new training run from pretrained weights.

    Args:
        checkpoint_dir: Directory containing checkpoint
        model: FSDP model (will be filled with loaded weights)
        rank: Current rank
        world_size: Total number of ranks

    Side effects:
        - model parameters are updated in-place
        - optimizer and dataloader states are ignored

    Raises:
        ValueError: If checkpoint model_config doesn't match model's config
    """
    # Validate model config before loading
    _validate_model_config(checkpoint_dir, model, rank)

    # Storage precision: an init or an inference load may convert (it starts no optimizer state of the checkpoint's),
    # but says so — exact from bf16 to fp32, rounded the other way.
    changes = _dtype_changes(checkpoint_dir, "model", {k: v.dtype for k, v in get_model_state_dict(model).items()
                                                       if isinstance(v, torch.Tensor)})
    if changes and rank == 0:
        print(f"  note: converting on load, {_describe_changes(changes)}, {len(changes)} tensors")
    model.param_dtype_history = []       # weights only: a new run, with no storage history of its own yet

    # Use get_state_dict() to create proper template structure for model only
    # Pass empty list instead of None (get_state_dict expects iterable)
    model_state_dict, _ = get_state_dict(model, optimizers=[])

    # Build state_dict for DCP load (model only)
    state_dict = {
        "model": model_state_dict,
    }

    # DCP load (all ranks participate, each reads its own shard)
    dcp.load(
        state_dict=state_dict,
        storage_reader=FileSystemReader(checkpoint_dir),
    )

    # Use set_state_dict() to properly load into model
    # Pass empty list instead of None (set_state_dict expects iterable)
    set_state_dict(
        model,
        optimizers=[],
        model_state_dict=state_dict["model"],
        optim_state_dict=None,
    )

    print(f"[Rank {rank}] Loaded model weights from {checkpoint_dir}")


def find_latest_checkpoint(base_dir: str) -> Optional[str]:
    """
    Find the latest checkpoint directory in base_dir.

    Args:
        base_dir: Base directory containing checkpoint directories

    Returns:
        Path to latest checkpoint directory, or None if not found

    Example:
        base_dir = "/path/to/checkpoints"
        latest = find_latest_checkpoint(base_dir)
        # Returns: "/path/to/checkpoints/step_002000"

    Only complete checkpoints count. save_checkpoint_dcp writes meta.json last, after every rank's DCP shards, and
    every load reads meta.json first. So a step_* directory without it is a save that was interrupted, e.g. by a
    preemption. Such a directory is skipped with a warning and never deleted; the newest complete one is returned. If
    step_* directories exist but none is complete, this raises: "no checkpoint, start fresh" would silently restart
    a run that had progressed.
    """
    if not os.path.exists(base_dir):
        return None

    # Find all step_* directories
    pattern = os.path.join(base_dir, "step_*")
    checkpoint_dirs = glob.glob(pattern)

    if not checkpoint_dirs:
        return None

    # Extract step numbers and sort; a directory without meta.json is an interrupted save (see the docstring)
    checkpoints, incomplete = [], []
    for path in checkpoint_dirs:
        dirname = os.path.basename(path)
        match = re.fullmatch(r"step_(\d+)", dirname)
        if match:
            if not os.path.exists(os.path.join(path, "meta.json")):
                incomplete.append(path)
                continue
            step = int(match.group(1))
            checkpoints.append((step, path))

    if incomplete:
        print0(f"  ⚠️  Skipping {len(incomplete)} incomplete checkpoint dir(s) without meta.json (an interrupted "
               f"save?): {sorted(incomplete)}. Not deleted.")
        if not checkpoints:
            raise FileNotFoundError(
                f"{base_dir} has step_* directories but none is complete (no meta.json): {sorted(incomplete)}. "
                f"Refusing to start fresh over them; remove or repair them to proceed.")

    if not checkpoints:
        return None

    # Return the checkpoint with highest step number
    checkpoints.sort(key=lambda x: x[0], reverse=True)
    return checkpoints[0][1]


def resolve_checkpoint_path(
    resume_from: Optional[str],
    save_dir: Optional[str] = None,
    rank: int = 0
) -> Optional[str]:
    """
    Intelligently resolve checkpoint path with auto-detection support.

    This function provides smart checkpoint path resolution:
    1. If resume_from is None/empty -> return None (afresh run)
    2. If resume_from == "auto" -> check save_dir for latest checkpoint
       - If save_dir has checkpoints -> return latest
       - If save_dir doesn't exist or has no checkpoints -> return None (afresh run)
    3. If resume_from is an explicit path:
       - If path doesn't exist -> raise FileNotFoundError (fail-fast)
       - If path is a file -> raise NotADirectoryError (single-file checkpoints are not supported)
       - If path is a DCP checkpoint -> return it directly
       - If path is a directory with step_* subdirs -> auto-detect latest
       - Otherwise -> raise FileNotFoundError

    Args:
        resume_from: Path to checkpoint, directory, or "auto"
        save_dir: Directory where checkpoints are saved (required for "auto" mode)
        rank: Current rank (for printing messages on rank 0 only)

    Returns:
        Resolved checkpoint path, or None if no checkpoint found

    Raises:
        FileNotFoundError: If explicit path doesn't exist (fail-fast to prevent training mistakes)
        NotADirectoryError: If explicit path is a file
        ValueError: If resume_from is "auto" but save_dir is not provided

    Examples:
        # Auto-resume mode (afresh if no checkpoint, resume if found)
        resolve_checkpoint_path("auto", save_dir="checkpoints/d12_run1")
        # Prints: "🔄 Auto-resume: Found checkpoint in checkpoints/d12_run1"
        # Returns: "checkpoints/d12_run1/step_002000" (or None if no checkpoint)

        # Explicit DCP checkpoint (fail-fast if not found)
        resolve_checkpoint_path("checkpoints/step_001000")
        # Returns: "checkpoints/step_001000" (or raises FileNotFoundError)

        # Explicit directory (auto-detect latest, fail-fast if not found)
        resolve_checkpoint_path("checkpoints/d12_run1")
        # Prints: "📁 Auto-detected latest checkpoint: checkpoints/d12_run1/step_002000"
        # Returns: "checkpoints/d12_run1/step_002000" (or raises FileNotFoundError)

        # No resume
        resolve_checkpoint_path(None)
        # Returns: None
    """
    # Case 1: No resume path provided (afresh run)
    if not resume_from:
        return None

    # Case 2: Auto-resume mode
    if resume_from.lower() == "auto":
        # Auto mode requires save_dir
        if not save_dir:
            raise ValueError(
                "resume_from='auto' requires save_dir to be specified in checkpoint config"
            )

        # Expand environment variables in save_dir
        save_dir = os.path.expandvars(save_dir)

        # Check if save_dir exists
        if not os.path.exists(save_dir):
            # save_dir doesn't exist yet (first run) - start fresh
            if rank == 0:
                print(f"🆕 Auto-resume: No checkpoint directory found")
                print(f"   Directory: {save_dir}")
                print(f"   Starting fresh training")
            return None

        # Try to find latest checkpoint in save_dir
        latest_checkpoint = find_latest_checkpoint(save_dir)
        if latest_checkpoint:
            # Found checkpoint - resume from it
            if rank == 0:
                step_name = os.path.basename(latest_checkpoint)
                print(f"🔄 Auto-resume: Found checkpoint in {save_dir}")
                print(f"   Resuming from: {step_name}")
            return latest_checkpoint
        else:
            # save_dir exists but no checkpoints yet - start fresh
            if rank == 0:
                print(f"🆕 Auto-resume: No checkpoints found in {save_dir}")
                print(f"   Starting fresh training")
            return None

    # Case 3: Explicit path (fail-fast if doesn't exist)
    # Expand environment variables
    resume_from = os.path.expandvars(resume_from)

    # Path must exist (fail-fast to catch typos)
    if not os.path.exists(resume_from):
        raise FileNotFoundError(
            f"Checkpoint path does not exist: {resume_from}\n"
            f"Hint: Use checkpoint.resume_from=auto for automatic resume (will start fresh if no checkpoint exists)"
        )

    # Case 3a: Not a directory (e.g. an old single-file checkpoint)
    if not os.path.isdir(resume_from):
        raise NotADirectoryError(
            f"Checkpoint path is a file: {resume_from}\n"
            f"Expected a DCP checkpoint directory (one with meta.json) or a directory containing step_* "
            f"checkpoints; single-file checkpoints are not supported."
        )

    # Case 3b: Check if it's a DCP checkpoint directory
    # DCP checkpoints have meta.json and .metadata files
    meta_json = os.path.join(resume_from, "meta.json")
    if os.path.exists(meta_json):
        # It's a valid DCP checkpoint, return directly
        return resume_from

    # Case 3c: Check if directory contains step_* subdirectories
    latest_checkpoint = find_latest_checkpoint(resume_from)
    if latest_checkpoint:
        # Auto-detected latest checkpoint
        if rank == 0:
            step_name = os.path.basename(latest_checkpoint)
            print(f"📁 Auto-detected latest checkpoint: {latest_checkpoint}")
            print(f"   (from directory: {resume_from}, latest: {step_name})")
        return latest_checkpoint

    # Case 3d: Directory exists but no checkpoints found (fail-fast)
    raise FileNotFoundError(
        f"Directory exists but contains no valid checkpoints: {resume_from}\n"
        f"Hint: Use checkpoint.resume_from=auto for automatic resume (will start fresh if no checkpoint exists)"
    )


